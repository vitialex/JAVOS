def get_text(key, lang="es", **kwargs):
    """Obtiene el texto traducido para una clave e idioma dados."""
    lang_dict = TRANSLATIONS.get(lang, TRANSLATIONS["es"])
    template = lang_dict.get(key, TRANSLATIONS["es"].get(key, key))
    if kwargs:
        try:
            return template.format(**kwargs)
        except Exception:
            return template
    return template
